static int current_page; /* 0 volumes, 1 directory, 2 hex */
static int selected, first, total, depth, filesize, hex_offset;
static int current_volume;
static char path[256];
static const char *const volumes[]={
    "drv0","sys0","data0","data1","data2","crd0","crd1","crd2"
};

static unsigned slen(const char *s) { unsigned n=0;while(s[n])n++;return n; }
static void copy(char *out, const char *in,unsigned max)
{
    unsigned i=0;
    if(!max)return;
    while(in[i] && i<max-1){out[i]=in[i];i++;}
    out[i]=0;
}
static void append(char *dest,const char *part,unsigned max)
{
    unsigned i=slen(dest),j=0;
    while(part[j] && i+1<max)dest[i++]=part[j++];
    dest[i]=0;
}
static void emit(u8 cmd)
{
    PRDR=(u8)(PRDR&~16u);
    __asm__ volatile("synco":::"memory");
    LCD=cmd;
    __asm__ volatile("synco":::"memory");
    PRDR=(u8)(PRDR|16u);
    __asm__ volatile("synco":::"memory");
}
static void data(u16 pixel)
{
    LCD=pixel;
    __asm__ volatile("synco":::"memory");
}
static void clear(u16 color)
{
    for(int i=0;i<SCREEN_WIDTH*SCREEN_HEIGHT;i++)framebuffer[i]=color;
}
static void rect(int x0,int y0,int x1,int y1,u16 color)
{
    if(x0<0)x0=0; if(y0<0)y0=0;
    if(x1>=SCREEN_WIDTH)x1=SCREEN_WIDTH-1;
    if(y1>=SCREEN_HEIGHT)y1=SCREEN_HEIGHT-1;
    for(int y=y0;y<=y1;y++)
        for(int x=x0;x<=x1;x++)framebuffer[y*SCREEN_WIDTH+x]=color;
}
static void text(int x,int y,const char *string,u16 color)
{
    for(int i=0;string[i] && x+8<=SCREEN_WIDTH;i++,x+=8) {
        unsigned c=(u8)string[i];
        if(c<32 || c>=128)c='?';
        for(int yy=0;yy<8;yy++){
            u8 row=font8x8[c-32][yy];
            for(int xx=0;xx<8;xx++)if(row&(0x80u>>xx)) {
                if(x+xx>=0 && y+yy>=0 && y+yy<SCREEN_HEIGHT)
                    framebuffer[(y+yy)*SCREEN_WIDTH+x+xx]=color;
            }
        }
    }
}
static void uint_dec(unsigned value,char *buf)
{
    char tmp[12];unsigned count=0;
    do{tmp[count++]=(char)('0'+value%10);value/=10;}while(value);
    for(unsigned i=0;i<count;i++)buf[i]=tmp[count-i-1];
    buf[count]=0;
}
static void hexbyte(u8 byte,char *buf)
{
    static const char hex[]="0123456789ABCDEF";
    buf[0]=hex[byte>>4];buf[1]=hex[byte&15];buf[2]=0;
}
static void present(void)
{
    emit(0x2a); data(0); data(0); data(2); data(15);
    emit(0x2b); data(0); data(40); data(1); data(103);
    emit(0x2c);
    for(unsigned i=0;i<SCREEN_WIDTH*SCREEN_HEIGHT;i++)data(framebuffer[i]);
    emit(0x29);
}
static void render(void)
{
    clear(WHITE);
    rect(0,0,527,31,BLUE);
    text(12,11,"EXWord Explorer - UPDADN2",WHITE);
    rect(0,297,527,319,BLUE);
    text(10,304,"Read-only experimental boot  |  EXIT back",WHITE);

    if(current_page==0) {
        text(15,43,"Registered volumes",BLACK);
        text(15,63,"EXE attempts read-only directory access.",DARK);
        text(15,80,"E / Test Menu OS APIs are unverified.",DARK);
        for(int i=0;i<8;i++) {
            int y=107+i*21;
            if(i==selected)rect(8,y-3,500,y+14,LIGHT);
            text(20,y,volumes[i],i==selected?BLACK:DARK);
        }
    }
    else if(current_page==1) {
        text(13,43,directory,BLACK);
        if(total==0) text(15,79,error_text[0]?error_text:"Empty directory",DARK);
        for(int i=first;i<total && i<first+19;i++) {
            int y=63+(i-first)*12;
            if(i==selected)rect(5,y-2,522,y+10,LIGHT);
            text(11,y,folder[i]?"DIR":"FILE",DARK);
            text(69,y,names[i],BLACK);
        }
    }
    else if(current_page==2) {
        text(11,43,path,BLACK);
        char nbuf[16];uint_dec((unsigned)filesize,nbuf);
        text(11,60,"File size:",DARK);text(112,60,nbuf,BLACK);
        int n=filesize-hex_offset;
        if(n>192)n=192;
        for(int i=0;i<n;i++) {
            int y=87+(i/12)*12;
            int x=16+(i%12)*39;
            char hex[3];
            hexbyte(hexdata[i],hex);
            text(x,y,hex,BLACK);
        }
        text(11,286,"PgUp / PgDn browse bytes",DARK);
    }
    if(error_text[0] && current_page!=1)text(15,283,error_text,DARK);
    present();
}
/* The original EX-word scan matrix is twelve 8-bit rows stored in six
   sixteen-bit words (gint-exword keysc_scan). */
static int key(int row,int col)
{
    volatile u16 const *regs=(void *)0xa44b0000;
    u16 v=regs[row/2];
    return (v>>((row&1)*8+col))&1;
}
enum { K_NONE, K_UP, K_DOWN, K_EXE, K_EXIT, K_PAGEUP, K_PAGEDOWN };
static int keys_now(void)
{
    if(key(5,6))return K_EXIT;
    if(key(6,6))return K_EXE;
    if(key(7,6))return K_UP;
    if(key(6,7))return K_DOWN;
    if(key(3,7))return K_PAGEUP;
    if(key(4,7))return K_PAGEDOWN;
    return K_NONE;
}
static int next_key(void)
{
    /* Require release between presses. No timer or heap is used. */
    while(keys_now()!=K_NONE){}
    for(;;) {
        int k=keys_now();
        if(k!=K_NONE) {
            for(volatile unsigned n=0;n<25000;n++)__asm__ volatile("nop");
            return k;
        }
    }
}
static int directory_list(void)
{
    char pattern[260],found[256]={0};
    unsigned long kind=0;
    int handle=-1;
    copy(pattern,directory,sizeof pattern);
    append(pattern,"\\*",sizeof pattern);
    error_text[0]=0;
    int rc=exword_sys_findfirst(pattern,&handle,found,&kind);
    if(rc<0) {
        copy(error_text,"Directory empty or OS API missing",sizeof error_text);
        return 0;
    }
    total=0;
    do {
        if(total<72 && found[0] && found[0]!='.') {
            copy(names[total],found,sizeof names[total]);
            folder[total]=(kind==5);
            total++;
        }
        kind=0;
        found[0]=0;
        rc=exword_sys_findnext(handle,found,&kind);
    } while(rc>=0 && total<72);
    exword_sys_findclose(handle);
    selected=first=0;
    return total;
}
static void open_file(void)
{
    int fd=exword_sys_open(path,1);
    if(fd<0){copy(error_text,"Cannot open file",sizeof error_text);return;}
    filesize=exword_sys_get_filesize(fd);
    hex_offset=0;
    if(filesize>=0) {
        exword_sys_seek(fd,0,0);
        int n=exword_sys_read(fd,hexdata,filesize<192?filesize:192);
        if(n>=0)current_page=2;
    }
    exword_sys_close(fd);
}
static void read_hex(void)
{
    int fd=exword_sys_open(path,1);
    if(fd<0)return;
    exword_sys_seek(fd,hex_offset,0);
    exword_sys_read(fd,hexdata,(filesize-hex_offset)<192?(filesize-hex_offset):192);
    exword_sys_close(fd);
}
void main(void)
{
    current_page=0;
    selected=first=total=depth=filesize=hex_offset=current_volume=0;
    directory[0]=path[0]=error_text[0]=0;
    for(;;) {
        render();
        int k=next_key();
        if(current_page==0) {
            if(k==K_UP && selected>0)selected--;
            else if(k==K_DOWN && selected<7)selected++;
            else if(k==K_EXE) {
                current_volume=selected;
                directory[0]='\\';directory[1]='\\';directory[2]=0;
                append(directory,volumes[selected],sizeof directory);
                depth=0;current_page=1;directory_list();
            }
        }
        else if(current_page==1) {
            if(k==K_UP && selected>0)selected--;
            else if(k==K_DOWN && selected<total-1)selected++;
            else if(k==K_PAGEUP)selected=selected>19?selected-19:0;
            else if(k==K_PAGEDOWN && total)
                selected+19<total ? (selected+=19) : (selected=total-1);
            else if(k==K_EXIT) {
                int i=(int)slen(directory)-1;
                while(i>=2 && directory[i]!='\\')i--;
                if(i<2) {current_page=0;selected=current_volume;}
                else {directory[i]=0;directory_list();}
            }
            else if(k==K_EXE && selected<total) {
                copy(path,directory,sizeof path);
                append(path,"\\",sizeof path);
                append(path,names[selected],sizeof path);
                if(folder[selected]) {
                    copy(directory,path,sizeof directory);
                    directory_list();
                }
                else open_file();
            }
            if(selected<first)first=selected;
            else if(selected>=first+19)first=selected-18;
        }
        else if(current_page==2) {
            if(k==K_EXIT) {current_page=1;directory_list();}
            else if(k==K_PAGEUP && hex_offset>0) {
                hex_offset=hex_offset>=192?hex_offset-192:0;read_hex();
            }
            else if(k==K_PAGEDOWN && hex_offset+192<filesize) {
                hex_offset+=192;read_hex();
            }
        }
    }
}
